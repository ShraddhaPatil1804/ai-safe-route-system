import os
import json
from typing import Dict, List, Any, Union
import numpy as np
import pandas as pd
import joblib

from backend.app.ml.config import (
    MODEL_PATH,
    METADATA_PATH,
    ALL_FEATURE_COLUMNS,
    get_crime_risk_category
)

DEFAULT_FEATURE_VALUES = {
    "crime_count": 0,
    "recent_crime_count": 0,
    "crime_density": 0.0,
    "average_severity": 0.0,
    "night_crime_ratio": 0.0,
    "min_crime_distance": 5000.0,
    "length": 25.0,
    "road_type_risk": 5.0,
    "lighting_risk": 15.0,
    "is_residential": 0,
    "is_oneway": 0,
    "speed_kph": 25.0,
    "police_distance": 1500.0,
    "hospital_distance": 1200.0,
    "pharmacy_distance": 800.0,
    "commercial_density": 0.0,
    "isolation_risk": 10.0,
    "bar_count": 0,
    "liquor_shop_count": 0
}


class CrimeRiskPredictor:
    """
    Singleton inference class for scoring road segments using the trained
    Random Forest Crime Risk model.
    """
    _instance = None

    def __init__(self):
        self.model = None
        self.metadata = None
        self.feature_names = list(ALL_FEATURE_COLUMNS)
        self.is_loaded = False

    @classmethod
    def get_instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def load_model(self):
        if self.is_loaded:
            return

        if not os.path.exists(MODEL_PATH):
            raise FileNotFoundError(
                f"Trained Random Forest model not found at {MODEL_PATH}. "
                "Run `python scripts/07_train_model.py` to train and save the model."
            )

        self.model = joblib.load(MODEL_PATH)
        if os.path.exists(METADATA_PATH):
            with open(METADATA_PATH, "r", encoding="utf-8") as f:
                self.metadata = json.load(f)
                if "feature_names" in self.metadata:
                    self.feature_names = self.metadata["feature_names"]

        self.is_loaded = True

    def predict(self, data: Union[Dict[str, Any], List[Dict[str, Any]], pd.DataFrame]) -> Union[Dict[str, Any], List[Dict[str, Any]]]:
        """
        Generates continuous crime risk prediction score [0.0 - 100.0]
        and categorizes into Low / Medium / High.
        """
        if not self.is_loaded:
            self.load_model()

        single_input = isinstance(data, dict)
        if single_input:
            records = [data]
        elif isinstance(data, pd.DataFrame):
            records = data.to_dict(orient="records")
        elif isinstance(data, list):
            records = data
        else:
            raise ValueError("Input data must be a dictionary, list of dictionaries, or a pandas DataFrame.")

        # Build feature rows with strict column ordering and default imputation
        rows = []
        for rec in records:
            row = []
            for col in self.feature_names:
                val = rec.get(col, DEFAULT_FEATURE_VALUES.get(col, 0.0))
                if val is None or (isinstance(val, float) and (np.isnan(val) or np.isinf(val))):
                    val = DEFAULT_FEATURE_VALUES.get(col, 0.0)
                row.append(float(val))
            rows.append(row)

        X = pd.DataFrame(rows, columns=self.feature_names)
        raw_predictions = self.model.predict(X)
        clipped_predictions = np.clip(raw_predictions, 0.0, 100.0)


        results = []
        for i, score in enumerate(clipped_predictions):
            score_round = round(float(score), 2)
            results.append({
                "predicted_crime_risk_score": score_round,
                "crime_risk_category": get_crime_risk_category(score_round),
                "is_development_prediction": True,
                "disclaimer": "DEVELOPMENT PREDICTION — BASED ON SYNTHETIC DATA"
            })

        return results[0] if single_input else results


